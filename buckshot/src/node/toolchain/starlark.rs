pub struct TypescriptRenderInput<'a> {
    pub version: &'a str,
    pub host_triples: &'a [String],
    pub components: &'a [Component],
}

/// Renders one TypeScript release: an `http_archive` per host of that
/// host's `@typescript/typescript-<platform>` native package (a
/// self-contained `lib/tsc` + `lib/*.d.ts`), plus the
/// `node_host_bundle` (`:typescript-host`) node toolchain instances
/// reference. No `downloaded_node_toolchain` call of its own -- the
/// node instance owns the toolchain, this file only supplies an attr.
pub fn render_typescript(input: TypescriptRenderInput) -> anyhow::Result<String> {
    let TypescriptRenderInput {
        version,
        host_triples,
        components,
    } = input;

    if host_triples.is_empty() {
        anyhow::bail!("at least one host triple is required");
    }

    let mut out = String::new();
    out.push_str(&format!(
        "# @generated by buckshot's `node typescript` command -- do not edit by hand.\n# Release: https://registry.npmjs.org/@typescript/typescript-darwin-arm64/-/typescript-darwin-arm64-{version}.tgz (plus the matching per-host native package)\n\n"
    ));
    out.push_str("load(\"@prelude//:rules.bzl\", \"http_archive\")\n");
    out.push_str(
        "load(\"@buckshot//node/toolchain:node_toolchain.bzl\", \"node_host_bundle\")\n\n",
    );

    let mut parts: Vec<String> = Vec::new();

    for comp in components {
        parts.push(http_archive_for(comp));
    }

    let (archive_map, path_style_map) = host_bundle_maps(host_triples, components)?;

    parts.push(
        serde_starlark::to_string(&NodeHostBundle {
            name: "typescript-host".to_string(),
            archive: Select(archive_map),
            path_style: Select(path_style_map),
            visibility: vec!["PUBLIC".to_string()],
        })
        .expect("NodeHostBundle always serializes"),
    );

    out.push_str(&parts.join("\n"));
    if !out.ends_with('\n') {
        out.push('\n');
    }
    Ok(out)
}

#[derive(Serialize)]
#[serde(rename = "alias")]
struct Alias {
    name: String,
    actual: String,
    visibility: Vec<String>,
}

/// `(major, minor, patch)` version key for an `X.Y.Z` release identifier.
fn typescript_version_key(name: &str) -> Option<(u64, u64, u64)> {
    crate::releases::semver_key(name)
}

/// Renders the rolling-alias BUCK file for the given TypeScript releases:
/// one `<major>` alias per major line, each pointing at the latest
/// release's `:typescript-host` bundle on that line.
pub fn render_typescript_aliases(releases: &[String]) -> String {
    let mut by_major: BTreeMap<u64, Vec<&String>> = BTreeMap::new();
    for release in releases {
        if let Some((major, _, _)) = typescript_version_key(release) {
            by_major.entry(major).or_default().push(release);
        }
    }
    for patches in by_major.values_mut() {
        patches.sort_by_key(|v| typescript_version_key(v));
    }

    let mut sorted: Vec<&String> = releases.iter().collect();
    sorted.sort_by_key(|v| typescript_version_key(v));

    let mut out = String::new();
    out.push_str("# @generated by buckshot's `node typescript` command -- do not edit by hand.\n");
    out.push_str(&format!(
        "# Releases: {}\n\n",
        sorted
            .iter()
            .map(|v| v.as_str())
            .collect::<Vec<_>>()
            .join(", ")
    ));
    out.push_str("load(\"@prelude//:rules.bzl\", \"alias\")\n\n");

    let mut parts: Vec<String> = Vec::new();
    for (major, patches) in &by_major {
        let latest = patches.last().expect("non-empty patch list");
        parts.push(
            serde_starlark::to_string(&Alias {
                name: format!("{major}"),
                actual: format!(
                    "buckshot//node/typescript/toolchains/{latest}:typescript-host"
                ),
                visibility: vec!["PUBLIC".to_string()],
            })
            .expect("Alias always serializes"),
        );
    }

    out.push_str(&parts.join("\n"));
    if !out.ends_with('\n') {
        out.push('\n');
    }
    out
}

/// Re-renders `dir/BUCK` (the rolling `<major>` aliases) from the
/// TypeScript releases on disk.
pub fn refresh_typescript_aliases(dir: &std::path::Path) -> anyhow::Result<()> {
    let releases = crate::releases::scan_releases(dir)?;
    for release in &releases {
        if typescript_version_key(release).is_none() {
            anyhow::bail!("{}/{release} is not an X.Y.Z release", dir.display());
        }
    }
    if releases.is_empty() {
        eprintln!(
            "node typescript: no releases under {}, leaving {}/BUCK unchanged",
            dir.display(),
            dir.display()
        );
        return Ok(());
    }
    let rendered = render_typescript_aliases(&releases);
    std::fs::write(dir.join("BUCK"), rendered)
        .with_context(|| format!("writing {}/BUCK", dir.display()))?;
    eprintln!(
        "node typescript: refreshed {}/BUCK ({})",
        dir.display(),
        releases.join(", ")
    );
    Ok(())
}

