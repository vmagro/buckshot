use std::collections::BTreeMap;

use anyhow::Context;
use serde::Serialize;

use super::manifest;
use super::manifest::Component;

#[derive(Serialize)]
#[serde(rename = "http_archive")]
struct HttpArchive {
    name: String,
    urls: Vec<String>,
    sha256: String,
    size_bytes: u64,
    strip_prefix: String,
    #[serde(rename = "type")]
    kind: String,
    visibility: Vec<String>,
}

#[derive(Serialize)]
#[serde(rename = "select")]
struct Select<T>(BTreeMap<String, T>);

#[derive(Serialize)]
#[serde(rename = "node_host_bundle")]
struct NodeHostBundle {
    name: String,
    archive: Select<String>,
    path_style: Select<String>,
    visibility: Vec<String>,
}

#[derive(Serialize)]
#[serde(rename = "downloaded_node_toolchain")]
struct DownloadedNodeToolchain {
    name: String,
    host: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    typescript: Option<String>,
    visibility: Vec<String>,
}

fn http_archive_for(comp: &Component) -> String {
    serde_starlark::to_string(&HttpArchive {
        name: comp.target_name.clone(),
        urls: vec![comp.url.clone()],
        sha256: comp.sha256.clone(),
        size_bytes: comp.size_bytes.expect("fetch_sizes runs before rendering"),
        strip_prefix: comp.strip_prefix.clone(),
        kind: comp.kind.to_string(),
        visibility: vec![],
    })
    .expect("HttpArchive always serializes")
}

/// Target label for the canonical `config_setting` in
/// platforms/configs/BUCK matching a (cpu, os) pair.
fn platform_target(cpu: &str, os_name: &str) -> String {
    format!(
        "buckshot//platforms/configs:{}",
        manifest::platform_label(cpu, os_name)
    )
}

pub struct RenderInput<'a> {
    pub version: &'a str,
    pub host_triples: &'a [String],
    pub components: &'a [Component],
    /// TypeScript major line (e.g. `"7"`) for the toolchain's `tsc`, or
    /// `None` for a tsc-less toolchain.
    pub typescript_version: Option<&'a str>,
}

/// Shared host-bundle rendering: flat `select()`s over the host triples'
/// config labels, resolved in the *execution* platform via
/// `attrs.exec_dep` (see `render`).
fn host_bundle_maps(
    host_triples: &[String],
    components: &[Component],
) -> anyhow::Result<(BTreeMap<String, String>, BTreeMap<String, String>)> {
    let mut archive_map = BTreeMap::new();
    let mut path_style_map = BTreeMap::new();
    for (triple, comp) in host_triples.iter().zip(components) {
        let (cpu, os_name) = manifest::platform_for(triple)?;
        let label = platform_target(cpu, os_name);
        archive_map.insert(label.clone(), format!(":{}", comp.target_name));
        let path_style = match os_name {
            "windows" => "windows",
            _ => "unix",
        };
        path_style_map.insert(label, path_style.to_string());
    }
    Ok((archive_map, path_style_map))
}

pub fn render(input: RenderInput) -> anyhow::Result<String> {
    let RenderInput {
        version,
        host_triples,
        components,
        typescript_version,
    } = input;

    if host_triples.is_empty() {
        anyhow::bail!("at least one host triple is required");
    }

    let mut out = String::new();
    out.push_str(&format!(
        "# @generated by buckshot's `node toolchain` command -- do not edit by hand.\n# Release: https://nodejs.org/dist/{version}/\n\n"
    ));
    out.push_str("load(\"@prelude//:rules.bzl\", \"http_archive\")\n");
    out.push_str(
        "load(\"@buckshot//node/toolchain:node_toolchain.bzl\", \"downloaded_node_toolchain\", \"node_host_bundle\")\n\n",
    );

    let mut parts: Vec<String> = Vec::new();

    for comp in components {
        parts.push(http_archive_for(comp));
    }

    // Host-keyed selects, resolved in the *execution* platform: the
    // toolchain pulls the bundle in via `attrs.exec_dep`, so these fire
    // against the build host even when the toolchain itself is analyzed
    // in an exotic target configuration (e.g. OS-less wasm32) -- the same
    // `host_bundle` pattern `rust/toolchain` and `cxx/toolchain` use.
    let (archive_map, path_style_map) = host_bundle_maps(host_triples, components)?;

    parts.push(
        serde_starlark::to_string(&NodeHostBundle {
            name: "host".to_string(),
            archive: Select(archive_map),
            path_style: Select(path_style_map),
            visibility: vec![],
        })
        .expect("NodeHostBundle always serializes"),
    );

    parts.push(
        serde_starlark::to_string(&DownloadedNodeToolchain {
            name: "toolchain".to_string(),
            host: ":host".to_string(),
            typescript: typescript_version.map(|v| {
                format!("buckshot//node/typescript/toolchains:{v}")
            }),
            visibility: vec!["PUBLIC".to_string()],
        })
        .expect("DownloadedNodeToolchain always serializes"),
    );

    out.push_str(&parts.join("\n"));
    if !out.ends_with('\n') {
        out.push('\n');
    }
    Ok(out)
}

