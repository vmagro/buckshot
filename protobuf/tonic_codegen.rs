//! Tonic codegen invoked by the `protobuf_library` macro's `tonic` language.
//!
//! Takes proto sources + a list of import roots on the CLI, runs
//! `tonic-prost-build` (prost messages + gRPC server) into a tempdir, and
//! emits a single self-contained `lib.rs` containing every package's
//! generated code. Sibling to `proto_codegen.rs`, which emits prost messages
//! only.

use std::ffi::OsStr;
use std::fmt::Write;
use std::fs;
use std::path::PathBuf;

use anyhow::Context;
use anyhow::Result;
use anyhow::bail;
use clap::Parser;
use tempfile::tempdir;

#[derive(Parser, Debug)]
#[command(about = "Compile .proto sources into a single tonic lib.rs")]
struct Args {
    /// Output path for the generated `lib.rs`.
    #[arg(long)]
    out: PathBuf,

    /// Path to the `protoc` binary to use. Required: without it,
    /// prost-build falls back to an ambient `protoc` on `PATH`, which a
    /// hermetic build must never depend on.
    #[arg(long)]
    protoc: PathBuf,

    /// Import roots. Pass once per `-I` directory.
    #[arg(long = "proto-path")]
    proto_paths: Vec<PathBuf>,

    /// Proto sources to compile. Paths must be resolvable against one of `--proto-path`.
    protos: Vec<PathBuf>,
}

fn main() -> Result<()> {
    let args = Args::parse();

    if args.protos.is_empty() {
        bail!("no .proto files provided");
    }

    let tmp = tempdir()?;

    let mut prost_config = prost_build::Config::new();
    prost_config.protoc_executable(&args.protoc);
    tonic_prost_build::configure()
        .build_server(true)
        .build_client(false)
        .out_dir(tmp.path())
        .compile_with_config(prost_config, &args.protos, &args.proto_paths)
        .context("tonic codegen failed")?;

    let mut lib = String::new();
    writeln!(lib, "//! Generated by buckshot's tonic_codegen — do not edit.")?;
    writeln!(lib, "#![allow(dead_code, clippy::all)]")?;
    writeln!(lib)?;

    let mut packages: Vec<String> = Vec::new();
    for entry in fs::read_dir(tmp.path())? {
        let entry = entry?;
        let path = entry.path();
        if path.extension() == Some(OsStr::new("rs"))
            && let Some(stem) = path.file_stem().and_then(|s| s.to_str())
        {
            packages.push(stem.to_string());
        }
    }
    packages.sort();

    // Inline each tonic-emitted `<package>.rs` directly at the top level of
    // the generated crate so consumers see types as `my_proto::Pose2d`
    // rather than `my_proto::my::pkg::Pose2d`.
    for pkg in &packages {
        let pkg_path = tmp.path().join(format!("{pkg}.rs"));
        let pkg_src = fs::read_to_string(&pkg_path)
            .with_context(|| format!("reading tonic output {}", pkg_path.display()))?;
        writeln!(lib, "// --- {pkg} ---")?;
        lib.push_str(&pkg_src);
        writeln!(lib)?;
    }

    std::fs::write(&args.out, lib.as_bytes())
        .with_context(|| format!("writing {}", args.out.display()))?;

    Ok(())
}
